"""
Usage Tracking Models
=====================

This module tracks token usage for AI operations (chat and embeddings) to enable:
- Billing and cost management
- Usage analytics and reporting
- Rate limiting and quota enforcement
- Historical usage trends

Model Hierarchy:
    Project (from accounts)
        └── UsageEvent (individual token usage events)
        └── UsageCounter (aggregated usage per time period)
"""

import uuid
from django.db import models
from accounts.models import Project


class UsageCounter(models.Model):
	"""
	Aggregated token usage counters for a project within a specific time period.
	
	Purpose:
	    - Efficiently track total token usage without scanning all individual events
	    - Enable fast billing calculations and quota checks
	    - Support time-based usage reporting (daily, monthly, etc.)
	    - Pre-aggregate data for analytics dashboards
	
	Data Stored:
	    - project: The project this usage belongs to
	    - period_start: Start of the usage period (e.g., beginning of day/month)
	    - period_end: End of the usage period (e.g., end of day/month)
	    - input_tokens: Total tokens sent to LLM (user prompts + system prompts + RAG context)
	    - output_tokens: Total tokens generated by LLM (AI responses)
	    - embedding_tokens: Total tokens used for vector embeddings (document ingestion)
	    - last_event_at: Timestamp of most recent usage event in this period
	
	Usage:
	    - Updated in real-time when UsageEvents are recorded
	    - Queried for billing calculations, quota checks, and analytics
	    - Periods typically align with billing cycles (monthly) or rate limits (hourly/daily)
	
	Token Costs (approximate for Google Gemini):
	    - Input tokens: ~$0.00015 per 1K tokens
	    - Output tokens: ~$0.0006 per 1K tokens
	    - Embedding tokens: ~$0.00001 per 1K tokens
	
	Example Query:
	    # Get current month usage for a project
	    from django.utils import timezone
	    month_start = timezone.now().replace(day=1, hour=0, minute=0, second=0)
	    usage = UsageCounter.objects.filter(
	        project=project,
	        period_start__gte=month_start
	    ).aggregate(
	        total_input=Sum('input_tokens'),
	        total_output=Sum('output_tokens')
	    )
	
	Constraints:
	    - Unique together: (project, period_start, period_end)
	    - Ensures only one counter per project per time period
	"""
	id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
	project = models.ForeignKey(Project, on_delete=models.CASCADE, related_name="usage_counters")
	period_start = models.DateTimeField()
	period_end = models.DateTimeField()
	input_tokens = models.PositiveBigIntegerField(default=0)
	output_tokens = models.PositiveBigIntegerField(default=0)
	embedding_tokens = models.PositiveBigIntegerField(default=0)
	last_event_at = models.DateTimeField(null=True, blank=True)

	class Meta:
		unique_together = ("project", "period_start", "period_end")


class UsageEvent(models.Model):
	"""
	Individual token usage event recording each AI operation.
	
	Purpose:
	    - Detailed audit trail of all AI operations
	    - Enable granular usage analysis and debugging
	    - Support charge-back to specific features or conversations
	    - Provide data for cost optimization
	
	Data Stored:
	    - project: The project this event belongs to
	    - kind: Type of operation ("chat_in", "chat_out", "embed")
	    - tokens: Number of tokens consumed in this operation
	    - metadata: Additional context (conversation_id, document_id, model name, etc.)
	    - created_at: When this operation occurred
	
	Event Types:
	    - "chat_in": Tokens sent TO the LLM
	        * Includes user message, system prompt, conversation history, RAG context
	        * Triggered when user sends a message
	        * Metadata: {"conversation_id", "message_id", "model", "context_size"}
	    
	    - "chat_out": Tokens generated BY the LLM
	        * AI's response text
	        * Triggered when AI completes response generation
	        * Metadata: {"conversation_id", "message_id", "model"}
	    
	    - "embed": Tokens used for embedding generation
	        * Document text converted to vectors during ingestion
	        * Triggered during document upload and processing
	        * Metadata: {"document_id", "kb_id", "chunk_count", "model"}
	
	Usage Flow:
	    1. AI operation occurs (chat message or document ingestion)
	    2. UsageEvent created with token count and metadata
	    3. Corresponding UsageCounter updated (via signal or direct update)
	    4. Events available for detailed analysis and auditing
	
	Example:
	    # Record chat usage
	    UsageEvent.objects.create(
	        project=project,
	        kind="chat_in",
	        tokens=1250,
	        metadata={
	            "conversation_id": str(conv.id),
	            "message_id": str(msg.id),
	            "model": "gemini-2.5-flash",
	            "has_rag_context": True,
	            "context_docs": 3
	        }
	    )
	
	Retention:
	    - Events are kept for detailed analysis (configurable retention period)
	    - Old events can be archived or deleted after aggregation
	    - UsageCounters provide summary data for historical periods
	"""
	id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
	KIND_CHOICES = [
		("chat_in", "Chat Input"),
		("chat_out", "Chat Output"),
		("embed", "Embedding"),
		("image", "Image"),
	]
	project = models.ForeignKey(Project, on_delete=models.CASCADE, related_name="usage_events")
	kind = models.CharField(max_length=16, choices=KIND_CHOICES)
	tokens = models.PositiveIntegerField(default=0)
	metadata = models.JSONField(default=dict, blank=True)
	created_at = models.DateTimeField(auto_now_add=True)


